"""language_detector.py — Детектор мови для перевірки відповідності мов у текстових полях.

Модуль визначає мову тексту (російська або українська) та дозволяє перевірити,
чи відповідає текст очікуваній мові.
"""

import re
from typing import Literal

# Набори символів та слів, характерних для української та російської мов
# Ці символи унікальні для української мови (відсутні в російській)
UKRAINIAN_ONLY_CHARS = set("ґєії'ҐЄІЇʼ")

# Ці символи унікальні для російської мови (відсутні в українській)
RUSSIAN_ONLY_CHARS = set("ыэъЫЭЪ")

# Часто вживані слова української мови (лише ті, що відрізняються від російської)
UKRAINIAN_COMMON_WORDS = {
    "є", "та", "із", "з", "у", "від", "які", "який",
    "яка", "яке", "цей", "ця", "це", "ці", "його", "її", "їх",
    "доступний", "бюджетний", "потужний", "надійний",
    "роздільна", "здатність", "пам'ять", "пам'яттю",
    "поставки", "комплект", "ноутбук", "тонкий", "для",
}

# Часто вживані слова російської мови (лише ті, що відрізняються від української)
RUSSIAN_COMMON_WORDS = {
    "и", "с", "в", "от", "который", "которая", "которое",
    "этот", "эта", "это", "эти", "его", "ее", "их",
    "доступный", "бюджетный", "мощный", "надежный",
    "разрешение", "память", "памятью",
    "поставки", "комплект", "ноутбук", "тонкий", "для",
    "работы",
}


def detect_language(text: str) -> Literal["uk", "ru", "unknown"]:
    """Визначає мову тексту (українська або російська).
    
    Алгоритм:
        1. Перевіряє наявність унікальних символів української чи російської мови.
        2. Якщо унікальних символів немає, аналізує часто вживані слова.
        3. Якщо не вдається визначити — повертає "unknown".
    
    Аргументи:
        text: Текст для аналізу.
    
    Повертає:
        "uk" для української мови,
        "ru" для російської мови,
        "unknown" якщо мову визначити не вдалося.
    
    Приклад:
        detect_language("Ноутбук із SSD")  →  "uk" (через "із")
        detect_language("Ноутбук с SSD")   →  "ru" (через "с")
        detect_language("Laptop SSD")      →  "unknown" (латиниця)
    """
    if not isinstance(text, str) or not text.strip():
        return "unknown"
    
    text = text.strip().lower()
    
    # Крок 1: Перевірка унікальних символів
    text_chars = set(text)
    
    # Якщо є символи, унікальні для української — це українська
    if text_chars & UKRAINIAN_ONLY_CHARS:
        return "uk"
    
    # Якщо є символи, унікальні для російської — це російська
    if text_chars & RUSSIAN_ONLY_CHARS:
        return "ru"
    
    # Крок 2: Аналіз часто вживаних слів
    # Розбиваємо текст на слова (алфавітно-цифрові послідовності)
    words = set(re.findall(r'\b[а-яёіїєґ]+\b', text, re.UNICODE))
    
    if not words:
        # Немає кириличних слів — не можемо визначити
        return "unknown"
    
    # Підраховуємо збіги з часто вживаними словами
    uk_score = len(words & UKRAINIAN_COMMON_WORDS)
    ru_score = len(words & RUSSIAN_COMMON_WORDS)
    
    # Якщо є чіткий переможець
    if uk_score > ru_score:
        return "uk"
    if ru_score > uk_score:
        return "ru"
    
    # Крок 3: Якщо рахунок однаковий або немає збігів — невідомо
    return "unknown"


def check_language_consistency(
    ru_text: str,
    uk_text: str,
    allow_empty: bool = True
) -> tuple[bool, str]:
    """Перевіряє відповідність мов у парі російський/український текст.
    
    Перевіряє, чи відповідає текст очікуваній мові:
    - ru_text має бути російською
    - uk_text має бути українською
    
    Аргументи:
        ru_text: Текст, який повинен бути російською.
        uk_text: Текст, який повинен бути українською.
        allow_empty: Дозволити порожні поля (за замовчуванням True).
    
    Повертає:
        Кортеж (is_valid, error_message).
        is_valid=True якщо мови відповідають очікуваним.
        error_message містить опис помилки, якщо is_valid=False.
    
    Приклад:
        check_language_consistency("Ноутбук с SSD", "Ноутбук із SSD")
        →  (True, "")
        
        check_language_consistency("Ноутбук із SSD", "Laptop SSD")
        →  (False, "Російська версія: виявлено українську; Українська версія: мову не визначено")
    """
    errors = []
    
    # Перевірка російської версії
    if not ru_text.strip():
        if not allow_empty:
            errors.append("Російська версія: порожнє поле")
    else:
        ru_lang = detect_language(ru_text)
        if ru_lang == "uk":
            errors.append("Російська версія: виявлено українську мову")
        elif ru_lang == "unknown":
            # Не завжди помилка — може бути багато латиниці
            pass
    
    # Перевірка української версії
    if not uk_text.strip():
        if not allow_empty:
            errors.append("Українська версія: порожнє поле")
    else:
        uk_lang = detect_language(uk_text)
        if uk_lang == "ru":
            errors.append("Українська версія: виявлено російську мову")
        elif uk_lang == "unknown":
            # Не завжди помилка — може бути багато латиниці
            pass
    
    if errors:
        return False, "; ".join(errors)
    return True, ""
